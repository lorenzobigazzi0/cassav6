is_managed_process() {
  local pid="$1"
  local process_cwd process_exe expected_exe
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  process_cwd="$(readlink -e "/proc/$pid/cwd" 2>/dev/null || true)"
  process_exe="$(readlink -e "/proc/$pid/exe" 2>/dev/null || true)"
  expected_exe="$(readlink -e "$NODE_BIN" 2>/dev/null || true)"
  [[ -n "$process_cwd" && -n "$process_exe" && -n "$expected_exe" ]] &&
    [[ "$process_cwd" == "$APP_ROOT" || "$process_cwd" == "$APP_ROOT/"* ]] &&
    [[ "$process_exe" == "$expected_exe" ]]
}

stop_pid_file() {
  local pid_file="$1"
  if [[ ! -f "$pid_file" ]]; then
    return 0
  fi
  local pid start_identity current_identity
  pid="$(cat "$pid_file" 2>/dev/null || true)"
  if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
    if ! is_managed_process "$pid"; then
      echo "Ignoring stale or foreign pid $pid from $pid_file" >&2
      rm -f "$pid_file"
      return 0
    fi
    start_identity="$(awk '{ print $22 }' "/proc/$pid/stat" 2>/dev/null || true)"
    echo "Stopping pid $pid from $pid_file"
    kill "$pid" 2>/dev/null || true
    sleep 1
    if kill -0 "$pid" 2>/dev/null; then
      current_identity="$(awk '{ print $22 }' "/proc/$pid/stat" 2>/dev/null || true)"
      if [[ -n "$start_identity" && "$current_identity" == "$start_identity" ]] &&
         is_managed_process "$pid"; then
        kill -9 "$pid" 2>/dev/null || true
      fi
    fi
  fi
  rm -f "$pid_file"
}

stop_port() {
  local port="$1"
  if ss -ltnH "sport = :$port" 2>/dev/null | grep -q .; then
    echo "Porta gia occupata, avvio annullato: $port" >&2
    exit 1
  fi
}

wait_http() {
  local url="$1"
  local label="$2"
  local curl_args=(-fsS --max-time 3)
  if [[ "$url" == https://* ]]; then
    curl_args=(-k -fsS --max-time 3)
  fi
  for _ in $(seq 1 60); do
    if curl "${curl_args[@]}" "$url" >/dev/null 2>&1; then
      echo "$label OK: $url"
      return 0
    fi
    sleep 1
  done
  echo "$label FAILED: $url" >&2
  return 1
}

select_lan_ip() {
  local candidate
  if [[ -n "${FRONTEND_LAN_IP:-}" ]] &&
     [[ -f "$APP_ROOT/mobile-frontend/certs/${FRONTEND_LAN_IP}.pem" ]] &&
     [[ -f "$APP_ROOT/mobile-frontend/certs/${FRONTEND_LAN_IP}-key.pem" ]]; then
    echo "$FRONTEND_LAN_IP"
    return 0
  fi
  for candidate in $(hostname -I 2>/dev/null || true); do
    if [[ -f "$APP_ROOT/mobile-frontend/certs/${candidate}.pem" ]] &&
       [[ -f "$APP_ROOT/mobile-frontend/certs/${candidate}-key.pem" ]]; then
      echo "$candidate"
      return 0
    fi
  done
  echo "192.168.0.28"
}

