  fi

  if [[ -n "${BACKEND_MULTI_PROCESS_ORDER_WORKER_ROUTE_ALLOWLIST:-}" ]]; then
    if printf '%s' "$audit_output" | "$NODE_BIN" -e 'const fs = require("node:fs"); const payload = JSON.parse(fs.readFileSync(0, "utf8")); process.exit(payload.orderWorkerAllowlistAudit?.goNoGo === "go" ? 0 : 1);'; then
      return 0
    fi
    echo "WARNING: order worker route allowlist audit is not GO; forcing BACKEND_MULTI_PROCESS_ORDER_WORKFLOW_AUDIT_GO=0 for this restart." >&2
    echo "WARNING: current audit summary: $(tr '\n' ' ' <<<"$audit_output" | sed -E 's/[[:space:]]+/ /g' | cut -c1-220)" >&2
    ORDER_WORKFLOW_AUDIT_GO_EFFECTIVE=0
    return 0
  fi

  if ! grep -q '"orderWorkersGoNoGo"[[:space:]]*:[[:space:]]*"go"' <<<"$audit_output"; then
    echo "WARNING: order workflow audit is not GO; forcing BACKEND_MULTI_PROCESS_ORDER_WORKFLOW_AUDIT_GO=0 for this restart." >&2
    echo "WARNING: current audit summary: $(tr '\n' ' ' <<<"$audit_output" | sed -E 's/[[:space:]]+/ /g' | cut -c1-220)" >&2
    ORDER_WORKFLOW_AUDIT_GO_EFFECTIVE=0
  fi
}

print_order_worker_prerequisites() {
  local requested=0
  local missing=0
  local name
  local prerequisites=(
    "BACKEND_MULTI_PROCESS_ORDER_WORKERS"
    "BACKEND_MULTI_PROCESS_ORDER_STATE_EXTERNALIZED"
    "BACKEND_APP_STATE_SPLIT_TABLE_STATES"
    "BACKEND_MYSQL_SPLIT_APP_STATE_DOMAINS"
    "BACKEND_RELATIONAL_ORDERS_WRITE_PRIMARY"
    "BACKEND_ORDERS_ASYNC_APPSTATE_FLUSH"
    "EVENT_OUTBOX_ENABLED"
    "BACKEND_MULTI_PROCESS_ORDER_WORKFLOW_AUDIT_GO"
    "BACKEND_MULTI_PROCESS_ORDER_WORKER_ROUTE_ALLOWLIST"
  )
  if [[ "${BACKEND_MULTI_PROCESS_ORDER_WORKER_ROUTE_ALLOWLIST:-}" == *"*"* ]]; then
    prerequisites+=("BACKEND_MULTI_PROCESS_ORDER_WORKER_ALLOW_WILDCARD")
  fi
  for name in "${prerequisites[@]}"; do
    local value="${!name:-0}"
    if [[ "$name" == "BACKEND_MULTI_PROCESS_ORDER_WORKFLOW_AUDIT_GO" ]]; then
      value="$ORDER_WORKFLOW_AUDIT_GO_EFFECTIVE"
    elif [[ "$name" == "BACKEND_MYSQL_SPLIT_APP_STATE_DOMAINS" ]]; then
      value="$MYSQL_APP_STATE_DOMAINS_FLAG"
    elif [[ "$name" == "EVENT_OUTBOX_ENABLED" ]]; then
      value="$EVENT_OUTBOX_FLAG"
    fi
    if [[ "$name" == "BACKEND_MULTI_PROCESS_ORDER_WORKER_ROUTE_ALLOWLIST" && -n "${!name:-}" ]]; then
      requested=1
    elif [[ "$name" == "BACKEND_APP_STATE_SPLIT_TABLE_STATES" && "$value" == "externalized" ]]; then
      requested=1
    elif [[ "$value" == "1" ]]; then
      requested=1
    fi
  done
  if [[ "$requested" != "1" ]]; then
    echo "Order workers: disabled (default safe owner routing)"
    return 0
  fi

  echo "Order worker prerequisites:"
  for name in "${prerequisites[@]}"; do
    local value="${!name:-0}"
    if [[ "$name" == "BACKEND_MULTI_PROCESS_ORDER_WORKFLOW_AUDIT_GO" ]]; then
      value="$ORDER_WORKFLOW_AUDIT_GO_EFFECTIVE"
    elif [[ "$name" == "BACKEND_MYSQL_SPLIT_APP_STATE_DOMAINS" ]]; then
      value="$MYSQL_APP_STATE_DOMAINS_FLAG"
    elif [[ "$name" == "EVENT_OUTBOX_ENABLED" ]]; then
      value="$EVENT_OUTBOX_FLAG"
    fi
    if [[ "$name" == "BACKEND_MULTI_PROCESS_ORDER_WORKER_ROUTE_ALLOWLIST" && -n "${!name:-}" ]]; then
      echo "- OK $name=${!name}"
    elif [[ "$name" == "BACKEND_APP_STATE_SPLIT_TABLE_STATES" && "$value" == "externalized" ]]; then
      echo "- OK $name=externalized"
    elif [[ "$value" == "1" ]]; then
      echo "- OK $name"
    else
      echo "- MISSING $name"
      missing=1
    fi
  done
  if [[ "$missing" == "1" ]]; then
    echo "WARNING: order workers requested partially; order mutations will stay routed to owner." >&2
    echo "WARNING: run cassa-frontend/scripts/order-workflow-externalization-audit.mjs and report:process-topology before enabling order workers." >&2
  else
    echo "Order workers: prerequisites complete; route guard may allow order-workflow on api-worker."
  fi
}

